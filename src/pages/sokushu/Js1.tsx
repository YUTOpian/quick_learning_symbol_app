      <P><code>while (条件) {'{ … }'}</code> は、条件が真の間、繰り返します。回数が決まっていないときに使います。<code>break</code> は繰り返し全体を終え、<code>continue</code> は今回の分だけ飛ばして、次の回へ進みます。</P>
