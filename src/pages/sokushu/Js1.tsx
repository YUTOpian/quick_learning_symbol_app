      <P>JSON は、オブジェクトや配列を<B>文字列で表現する形式</B>です。ネットワークでデータをやり取りするとき、実際に流れるのはこの文字列です。<code>JSON.stringify(値)</code> で値を文字列に、<code>JSON.parse(文字列)</code> で文字列を値に戻します。<code>JSON.stringify(値, null, 2)</code> とすると、字下げして見やすく整形します。JSONの項目名は、必ずダブルクォートで囲みます。壊れたJSONを <code>parse</code> すると <code>SyntaxError</code> になります。</P>
